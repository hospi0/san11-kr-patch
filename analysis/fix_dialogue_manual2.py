def main():
    dry = '--dry' in sys.argv
    lines = io.open(SRC, encoding='utf-8').read().split('\n')
    idxmap = {}
    for i, ln in enumerate(lines):
        p = ln.rstrip('\r').split('\t')
        if len(p) >= 5 and p[0].isdigit():
            idxmap[(p[0], p[1])] = i
    ok = 0
    fails = []
    for key, subs in E.items():
        if key not in idxmap:
            fails.append(('%s:%s' % key, '행없음', ''))
            continue
        i = idxmap[key]
        p = lines[i].split('\t')
        for sub in subs:
            old, new = sub[0], sub[1]
            all_ = len(sub) > 2 and sub[2] == 'ALL'
            c = p[4].count(old)
            if c == 0 or (c != 1 and not all_):
                fails.append(('%s:%s' % key, 'old %d회' % c, old))
                continue
            p[4] = p[4].replace(old, new)
            ok += 1
        lines[i] = '\t'.join(p)
    print('치환 성공 %d개 / 실패 %d개' % (ok, len(fails)))
    for k, r, o in fails:
        print('  실패 [%s] %s : %r' % (k, r, o))
    if dry:
        print('(--dry: 저장 안 함)')
        return
    shutil.copy(SRC, SRC + '.bak_manual2')
    io.open(SRC, 'w', encoding='utf-8', newline='').write('\n'.join(lines))
    print('저장 완료 (백업 %s.bak_manual2)' % SRC)


if __name__ == '__main__':
    main()
