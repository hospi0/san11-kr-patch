def apply(fn, edits, dry):
    path = os.path.join(REPO, 'work', fn)
    lines = open(path, encoding='utf-8').read().split('\n')
    n = 0
    for ln, old, new in edits:
        cols = lines[ln - 1].split('\t')
        if len(cols) < 5:
            raise SystemExit('%s:%d 열 부족' % (fn, ln))
        if old not in cols[4]:
            raise SystemExit('%s:%d 옛 문자열 없음: %r\n  실제: %s'
                             % (fn, ln, old, cols[4]))
        cols[4] = cols[4].replace(old, new)
        lines[ln - 1] = '\t'.join(cols)
        n += 1
    if not dry:
        bak = path + '.bak_end01'
        if not os.path.exists(bak):
            open(bak, 'w', encoding='utf-8').write(
                open(path, encoding='utf-8').read())
        open(path, 'w', encoding='utf-8').write('\n'.join(lines))
    print('%s: %d곳 %s' % (fn, n, '확인만(dry)' if dry else '수정'))
    return n


