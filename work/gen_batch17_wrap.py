TARGET = 21.0


def wrap(text):
    """글자 단위 그리디 wrap, 전각폭 기준. {N}으로 join."""
    lines, cur, w = [], '', 0.0
    for ch in text:
        cw = 1.0 if C.width(ch) or True else 0  # placeholder, real calc below
        cw = 1.0 if _is_wide(ch) else 0.5
        if w + cw > TARGET and cur:
            lines.append(cur)
            cur, w = '', 0.0
        cur += ch
        w += cw
    if cur:
        lines.append(cur)
    return '{N}'.join(lines)


def _is_wide(ch):
    import unicodedata as U
    return U.east_asian_width(ch) in 'WF'


