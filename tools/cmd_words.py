def words():
    """[(col, row, jp)] — 빈 칸 제외."""
    out = []
    for c, ws in sorted(GRID.items()):
        for r, w in enumerate(ws):
            if w:
                out.append((c, r, w))
    return out


def kr_of(jp, to_hangul):
    """(한글, 근거). 1:1이 아니면 호출부가 막는다."""
    if jp in OVERRIDES:
        return OVERRIDES[jp], "override"
    return to_hangul(jp), "auto"
