"""도움말(idx=3) 번역문을 entry3 예산에 맞춰 간결체로 압축한다.

★왜 필요한가: entry3의 RAM 슬롯은 **122,880 B 고정**이다(뒤에 entry4가 0x1cf4400에 딱 붙어
있어 넘으면 깔아뭉개고 죽는다 — 실기 2회로 확정, docs/11 참조). 파트1(조립테이블)이 97,417 B를
먹으므로 **평문 파트2 예산 = 20,745 B**(본문 18,456 + 05구분자 2,289). 존댓말 번역은 22,939 B라
20% 초과.

★예산은 **줄별이 아니라 총합**이다(오프셋 테이블을 새로 쓰므로). 긴 설명문은 살리고 반복되는
상투구를 집중적으로 깎는 게 이득이다 — `~없습니다` 174회, `~선택해 주세요` 72회처럼.

문체 = 게임 하단바 도움말이라 **명사형 간결체**가 자연스럽다. 시설효과 설명 때 쓴
「반각공백 1B + 명사구 요약체」와 같은 방침(tools/fac_desc.py).
"""
import re

JONG_B, JONG_M = 17, 16          # 한글 종성 인덱스: ㅂ=17, ㅁ=16


def _nominalize(m):
    """`~ㅂ니다` → `~ㅁ` 명사형 파생. 배웁니다→배움 · 올립니다→올림 · 돌아갑니다→돌아감.

    한글 조합: code = 0xAC00 + (초성*21 + 중성)*28 + 종성. 종성만 ㅂ→ㅁ으로 바꾸면 된다.
    개별 동사를 일일이 나열하는 대신 규칙 하나로 덮는다.
    """
    ch = m.group(1)
    o = ord(ch) - 0xAC00
    if o % 28 != JONG_B:
        return m.group(0)                    # 종성이 ㅂ이 아니면 건드리지 않음
    return chr(0xAC00 + o - JONG_B + JONG_M)


