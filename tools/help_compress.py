def _apply(chunk):
    for pat, rep in RULES:
        chunk = re.sub(pat, rep, chunk)
    return chunk


def compress(s):
    """한 줄 압축. 토큰({V:..}/{N}/{BTNxx})은 건드리지 않는다.

    규칙은 `$` 앵커라 '문장 끝'에만 걸린다. 토큰 경계뿐 아니라 **마침표와 여는 괄호로도 쪼개서**
    적용해야 문장 중간의 어미까지 잡힌다:
      「신무장을 선택합니다. 선택하지 않아도~」  ← 마침표 앞 문장
      「무장을 선택해 주세요(최대 3명)」        ← 괄호 앞 문장 (이게 23줄이나 됐다)
    """
    out = []
    for part in re.split(r"(\{[^}]+\})", s):     # ① 토큰 경계
        if part.startswith("{") or not part:
            out.append(part)
            continue
        # ② 마침표/여는괄호 경계 — 구분자를 유지한 채 각 조각의 끝에 규칙을 건다
        pieces = re.split(r"(\.\s*|\()", part)
        out.append("".join(p if i % 2 else _apply(p) for i, p in enumerate(pieces)))
    return re.sub(r" +", " ", "".join(out)).strip()


def body_bytes(s):
    """토큰 뺀 실제 인코딩 바이트 수(한글 2B, 그 외 1B)."""
    t = re.sub(r"\{[^}]+\}", "", s)
    return sum(2 if "가" <= c <= "힣" else 1 for c in t)
