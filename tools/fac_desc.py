# entry5에는 **한 문자열의 중간을 다른 시설이 자기 설명의 시작점으로 참조**하는 자리가 있다.
#   0x1180 「隣接マス部隊の進行を阻む壁」\0   ← 石壁 계열이 읽는 시작점
#   0x1188 「部隊の進行を阻む壁」            ← 土塁(설치 메뉴)가 읽는 시작점 = +8B
# 즉 0x1188은 독립 문자열이 아니라 **0x1180의 꼬리**다(파일에 따로 존재하지 않는다).
# 우리가 「인접칸 」(7B)으로 번역하자 +8이 「부」의 **두 번째 바이트**에 떨어져
# 깨진 글리프 + 「대 진행 저지 벽」이 됐다.
#
# 대책: 그런 문자열은 KR의 접두사 바이트 수를 JP와 **정확히 같게** 고정한다.
#       {JP 전체: (접두사 바이트수, 그 지점부터 시작해야 하는 KR 꼬리)}
PREFIX_LOCK = {
    "隣接マス部隊の進行を阻む壁": (8, "부대 진행 저지 벽"),
}


def check_prefix_locks(codec):
    """PREFIX_LOCK 위반 시 사유 리스트. 빌더가 호출해 게이트로 쓴다."""
    bad = []
    for jp, (nbytes, tail) in PREFIX_LOCK.items():
        kr = DESCRIPTIONS[jp]
        b = codec.encode(kr)
        tb = codec.encode(tail)
        if b[nbytes:nbytes + len(tb)] != tb:
            bad.append("%r: +%dB 지점이 %r 로 시작해야 하는데 %r"
                       % (jp, nbytes, tail, b[nbytes:nbytes + len(tb)]))
    return bad


def find_desc_offsets(ent, region=(0xb82, 0x3000)):
    """(rel_off, jp, budget) 리스트. budget = len(jp) + 뒤 슬랙."""
    lo, hi = region
    out = []
    for jp in DESCRIPTIONS:
        pat = jp.encode("cp932")
        i = lo
        while True:
            p = ent.find(pat, i, hi)
            if p < 0:
                break
            # 널종료 확인 + 슬랙 계산
            end = p + len(pat)
            if end < len(ent) and ent[end] == 0:
                slack = 0
                k = end
                while k < len(ent) and ent[k] == 0:
                    slack += 1; k += 1
                out.append((p, jp, len(pat) + slack, len(pat)))
            i = p + 1
    # ★오버랩 제거: 긴 매치 안에 포함된 짧은 매치 버림
    #   (예: 「１都市１つのみ」가 「港のある都市のみ。１都市１つのみ」 안에 있음)
    out.sort(key=lambda r: -r[3])          # 긴 것 먼저
    kept, claimed = [], []
    for p, jp, bud, plen in out:
        rng = (p, p + plen)
        if any(not (rng[1] <= c[0] or rng[0] >= c[1]) for c in claimed):
            continue                       # 이미 점유된 바이트와 겹침 → 스킵
        claimed.append(rng)
        kept.append((p, jp, bud))
    kept.sort()
    return kept


def kr_bytes(jp, codec):
    """KR을 cp932(운반체)로 인코딩. (bytes, kr) 또는 (None, kr)."""
    kr = DESCRIPTIONS[jp]
    try:
        b = codec.encode(kr)          # 반각 공백(1B) — 예산 절약
    except Exception:
        return None, kr
    return b, kr
